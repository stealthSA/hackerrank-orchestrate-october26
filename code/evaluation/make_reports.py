def pct(x):
    return f"{100 * x:.1f}%"


def table(m):
    rows = [("Cases", m["cases"]), ("Case-level status accuracy", pct(m["status_accuracy"])),
            ("Step precision", pct(m["step_precision"])), ("Step recall", pct(m["step_recall"])),
            ("Step F1", pct(m["step_f1"])),
            ("Sequence accuracy (exact ordered steps + status)", pct(m["sequence_exact_accuracy"])),
            ("Sequence similarity (LCS ratio)", pct(m["sequence_lcs_ratio"]))]
    rows += [(f"Field accuracy: {k}", pct(v)) for k, v in m["field_accuracy"].items()]
    return "| Metric | Value |\n| --- | --- |\n" + "\n".join(f"| {a} | {b} |" for a, b in rows)


def diffs(per_case):
    out = []
    for cid, ok, seq, extra, missing, ps, gs in per_case:
        if ok and seq:
            continue
        out.append(f"{cid}: predicted {ps}, label {gs}")
        out += [f"  + extra   {e}" for e in extra] + [f"  - missing {m}" for m in missing]
    return "\n".join(out) or "(none)"


